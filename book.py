"""
Здесь описано, как выглядит одна книга в нашей программе.

Записи сохраняются в SQLite (файл library.db) и дублируются
в бинарном дереве поиска для операций по заданию.
"""

from dataclasses import dataclass


@dataclass
class Book:
    """
    Запись о книге по условию задания.

    Поля соответствуют паспорту издания в библиотечном каталоге:
    классификация (УДК), автор, название, год, число экземпляров на полках.
    """

    # Номер УДК — как «адрес» книги в каталоге, по нему её ищут
    udc: str
    # Кто написал книгу (автор)
    author: str
    # Как книга называется
    title: str
    # В каком году напечатали
    year: int
    # Сколько таких книг лежит на полке в библиотеке
    copies: int

    def as_row(self) -> tuple[str, str, str, str, str]:
        """
        Готовит данные книги для показа в таблице на экране.

        Таблица умеет показывать только текст, поэтому год и число
        экземпляров превращаем в строки.
        """
        return (
            self.udc,
            self.author,
            self.title,
            str(self.year),
            str(self.copies),
        )
